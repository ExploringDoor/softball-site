#!/bin/sh
# Rebuild the Text a Score engine for DVSL from the portable core in
# league-platform (lib/sms/core, no outside imports except node:crypto):
#
#   api/_sms/core.js   ONE ESM bundle with everything the DVSL texting code uses:
#     score-inbound   handleInboundText, UNKNOWN_SENDER_REPLY, helpText, PENDING_MS, UNDO_MS
#     score-parser    normalizeText, teamAliases, bestTeamMatch, parseChoice, isQuestion
#     twilio-verify   twilioSignatureValid, twiml
#     consent         webConfirmText, isYesReply, ... (builder C: sms-optin / optin.js)
#     schedule-alerts planScheduleAlerts, describeChange, ... (builder C: sms-alerts)
#     delivery        delivery status -> a sentence (sms-status / admin Texts tab)
#     office-alerts   office alert wording
#     phone, time, field  toE164US, tenDigits, lastFour, formatTime12, shortField
#
# DVSL api files are ESM syntax (export default) under a "type":"commonjs"
# package; Vercel transpiles them, and api/_lib imports bundle fine. So this is
# --format=esm, unlike AFSF's CommonJS build.
#
# Then a few phrases are localized for DVSL (asserted, so a core rewrite that
# moves them fails loudly here instead of shipping the wrong wording):
#   * DVSL runs "first report posts". A second captain who DISAGREES is
#     recorded and the commissioner is told, but the score already up STAYS up
#     (captain.html submitScore). The core's reply says "the score is off the
#     site", which would be false here.
#   * DVSL has a commissioner, not a "league office", and captains, not coaches.
#
# Re-run after pulling parser fixes from league-platform.
# Requires ~/Desktop/league-platform with node_modules (esbuild).
set -e
LP="$HOME/Desktop/league-platform"
CORE="$LP/lib/sms/core"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$HERE/api/_sms/core.js"
ESB="$LP/node_modules/.bin/esbuild"; [ -x "$ESB" ] || ESB="esbuild"
mkdir -p "$HERE/api/_sms"

REV="$(cd "$LP" && git log -1 --format='%h %cd' --date=short -- lib/sms/core 2>/dev/null || echo unknown)"

# The entry lives in a temp file and imports the core by absolute path, so
# nothing is written into league-platform.
TMPD="$(mktemp -d)"
ENTRY="$TMPD/dvsl-sms-entry.ts"
trap 'rm -rf "$TMPD"' EXIT
cat > "$ENTRY" <<EOF
export * from "$CORE/score-inbound";
export {
  normalizeText, teamAliases, bestTeamMatch, parseChoice, parseCommand, parseQuery,
  isQuestion, isReaction, isAutoReply, interpret, startsAt, hasStarted, shiftDay,
} from "$CORE/score-parser";
export * from "$CORE/twilio-verify";
export * from "$CORE/consent";
export * from "$CORE/schedule-alerts";
export * from "$CORE/delivery";
export * from "$CORE/office-alerts";
export * from "$CORE/phone";
export * from "$CORE/time";
export * from "$CORE/field";
EOF

"$ESB" "$ENTRY" --bundle --format=esm --platform=node --target=node18 --log-level=warning \
  --outfile="$OUT" \
  --banner:js="// GENERATED by tools/build_sms_core.sh from league-platform lib/sms/core ($REV). Do not edit by hand."

python3 - "$OUT" <<'PY'
import sys
p = sys.argv[1]; s = open(p).read()
swaps = [
    # A disagreeing second report does NOT take the score down in DVSL.
    ("so the score is off the site until the league office settles it. They have been told.",
     "so it is flagged for the commissioner to settle. The score already on the site stays up until then. They have been told."),
    ("The league office", "The commissioner"),
    ("the league office", "the commissioner"),
    ("your league admin", "the commissioner"),
    # DVSL teams have captains, not coaches.
    ("The other coach", "The other captain"),
    ("the other coach", "the other captain"),
]
for a, b in swaps:
    assert a in s, "expected phrase not found: " + a
    s = s.replace(a, b)
left = s.count("league office")
assert left == 0, "unlocalized 'league office' left: %d" % left
open(p, "w").write(s)
print("localized", len(swaps), "phrase types for DVSL")
PY
echo "built api/_sms/core.js"
